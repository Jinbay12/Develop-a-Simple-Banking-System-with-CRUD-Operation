    /**
     * Pulls live account rows from your database and populates the table.
     */
    private void loadTableData() {
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(
            new Object[][] {}, 
            new String[] {"Account Number", "Customer Name", "Account Type", "Balance"}
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // Prevents manual editing inside cells
            }
        };

        String query = "SELECT * FROM accounts";

        try (java.sql.Connection conn = getConnection();
             java.sql.Statement stmt = conn.createStatement();
             java.sql.ResultSet rs = stmt.executeQuery(query)) {

            while (rs.next()) {
                String accountNum = rs.getString("account_number");
                String name = rs.getString("customer_name");
                String type = rs.getString("account_type");
                double balance = rs.getDouble("balance");

                model.addRow(new Object[]{accountNum, name, type, balance});
            }

            tblAccounts.setModel(model);

        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Error loading data from database: " + e.getMessage(), 
                "Database Error", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

