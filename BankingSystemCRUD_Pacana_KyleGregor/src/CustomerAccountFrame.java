    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
      String accountNum = txtAccountNum.getText().trim();
    String name = txtCustomerName.getText().trim();
    String type = cmbAccountType.getSelectedItem().toString();
    String balanceStr = txtBalance.getText().trim();

    if (accountNum.isEmpty() || name.isEmpty() || balanceStr.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select an account row first and modify fields!", "Validation Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    try {
        double balance = Double.parseDouble(balanceStr);
        String sql = "UPDATE accounts SET customer_name = ?, account_type = ?, balance = ? WHERE account_number = ?";
        
        try (java.sql.Connection conn = getConnection();
             java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {
            
            pstmt.setString(1, name);
            pstmt.setString(2, type);
            pstmt.setDouble(3, balance);
            pstmt.setString(4, accountNum);
            
            int rowsUpdated = pstmt.executeUpdate();
            if (rowsUpdated > 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Account updated successfully!");
                loadTableData(); // Refresh UI view
                btnClearActionPerformed(evt); // Clear inputs and restore fields
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Account number not found.", "Update Failed", javax.swing.JOptionPane.ERROR_MESSAGE);
            }
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Balance must be a valid decimal number!", "Input Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage(), "SQL Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
       String accountNum = txtAccountNum.getText().trim();

    if (accountNum.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select an account row from the table to delete!", "Validation Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    int confirmation = javax.swing.JOptionPane.showConfirmDialog(this, 
            "Are you absolutely sure you want to delete Account " + accountNum + "?", 
            "Confirm Deletion", javax.swing.JOptionPane.YES_NO_OPTION, javax.swing.JOptionPane.QUESTION_MESSAGE);

    if (confirmation == javax.swing.JOptionPane.YES_OPTION) {
        String sql = "DELETE FROM accounts WHERE account_number = ?";
        
        try (java.sql.Connection conn = getConnection();
             java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {
            
            pstmt.setString(1, accountNum);
            
            int rowsDeleted = pstmt.executeUpdate();
            if (rowsDeleted > 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "Account deleted successfully!");
                loadTableData(); // Refresh UI view
                btnClearActionPerformed(evt); // Reset form state
            }
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage(), "SQL Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void txtSearchKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtSearchKeyReleased
       String keyword = txtSearch.getText().trim();
    
    // Create a new table model structure
    javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(
        new Object[][] {}, 
        new String[] {"Account Number", "Customer Name", "Account Type", "Balance"}
    ) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false;
        }
    };

    // SQL query using LIKE operators to search by account number OR customer name
    String query = "SELECT * FROM accounts WHERE account_number LIKE ? OR customer_name LIKE ?";

    try (java.sql.Connection conn = getConnection();
         java.sql.PreparedStatement pstmt = conn.prepareStatement(query)) {
        
        // Use wildcards (%) for partial matching (e.g., typing "K" will match "Kyle")
        pstmt.setString(1, "%" + keyword + "%");
        pstmt.setString(2, "%" + keyword + "%");
        
        try (java.sql.ResultSet rs = pstmt.executeQuery()) {
            while (rs.next()) {
                String accountNum = rs.getString("account_number");
                String name = rs.getString("customer_name");
                String type = rs.getString("account_type");
                double balance = rs.getDouble("balance");

                model.addRow(new Object[]{accountNum, name, type, balance});
            }
        }
        
        // Bind the filtered results to your table component
        tblAccounts.setModel(model);

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Error filtering data: " + e.getMessage(), 
            "Search Error", 
            javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_txtSearchKeyReleased

