    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String accountNum = txtAccountNum.getText().trim();
        String name = txtCustomerName.getText().trim();
        String type = cmbAccountType.getSelectedItem().toString();
        String balanceStr = txtBalance.getText().trim();

        if (accountNum.isEmpty() || name.isEmpty() || balanceStr.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please fill out all fields!", "Validation Warning", java.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double balance = Double.parseDouble(balanceStr);
            String sql = "INSERT INTO accounts (account_number, customer_name, account_type, balance) VALUES (?, ?, ?, ?)";
            
            try (java.sql.Connection conn = getConnection();
                 java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {
                
                pstmt.setString(1, accountNum);
                pstmt.setString(2, name);
                pstmt.setString(3, type);
                pstmt.setDouble(4, balance);
                
                pstmt.executeUpdate();
                javax.swing.JOptionPane.showMessageDialog(this, "Account saved successfully!");
                
                loadTableData(); // Refresh spreadsheet
                btnClearActionPerformed(evt); // Clear inputs
            }
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Balance must be a valid decimal number!", "Input Error", java.swing.JOptionPane.ERROR_MESSAGE);
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage(), "SQL Error", java.sql.SQLException.ERROR_MESSAGE);
        }
    
    }//GEN-LAST:event_btnSaveActionPerformed

